// Налаштування
const CLICK_DELAY_MS = 100; 

// Нормалізація тексту для точного порівняння
function cleanText(t) {
    return t.replace(/\u00a0/g, " ")
            .replace(/\s+/g, " ")
            .trim();
}

// Рекурсивна функція збору всіх елементів варіантів відповідей з усіх iframe
function getAllOptionElements(doc = document) {
    let elements = Array.from(doc.querySelectorAll('[data-field="optionText"], .text.resizeable-text')); // Селектори тексту відповідей у Storyline
    
    const iframes = doc.querySelectorAll('iframe');
    for (let i = 0; i < iframes.length; i++) {
        try {
            const iframeDoc = iframes[i].contentDocument || iframes[i].contentWindow.document;
            if (iframeDoc) {
                elements = elements.concat(getAllOptionElements(iframeDoc));
            }
        } catch (e) {
            // Пропускаємо Cross-Origin фрейми, якщо такі є
        }
    }
    return elements;
}

let highlighted = 0;
let clicked = 0;
const toClick = [];

// Крок 1: Шукаємо та підсвічуємо збіги
const allOptions = getAllOptionElements();

allOptions.forEach(opt => {
    const optText = cleanText(opt.textContent);
    
    // Перевіряємо, чи є текст елемента в масиві правильних відповідей
    const isCorrect = correctAnswers.some(ans => cleanText(ans) === optText);
    
    if (isCorrect) {
        // Візуальне підсвічування
        opt.style.cssText = "background: #c8f7c5 !important; border: 2px solid #2ecc71 !important; border-radius: 4px; font-weight: bold;";
        highlighted++;

        // Розрахунок куди саме клікати (на випадок якщо кастомний тег не реагує на клік)
        const parentButton = opt.closest('button') || opt.closest('label') || opt.closest('.cs-button') || opt;
        toClick.push(parentButton);
    }
});

// Крок 2: Клікаємо по черзі із затримкою
function clickWithDelay(index) {
    if (index >= toClick.length) {
        console.log(`✅ Роботу завершено. Підсвічено: ${highlighted} | Клікнуто: ${clicked}`);
        return;
    }

    try {
        toClick[index].click();
        clicked++;
    } catch(e) {
        console.error("Помилка кліку на елемент:", toClick[index], e);
    }

    setTimeout(() => clickWithDelay(index + 1), CLICK_DELAY_MS);
}

// Старт
if (toClick.length > 0) {
    clickWithDelay(0);
} else {
    console.log("❌ Правильних відповідей на цьому слайді не знайдено.");
}